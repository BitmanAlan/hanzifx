/** 取词：sources 不给就是全部；比如 lexiconWords(['dev']) 只要开发集来的 */
export function lexiconWords(sources) {
  return LEXICON.filter(([, src]) => !sources || sources.some((s) => src.split('+').includes(s))).map(([w]) => w);
}

export const BUILTIN_WORDS = lexiconWords();

/**
 * 把 ICU 的词边界按词表校正：词表里的词在原文里出现时，去掉它内部的边界、补上它两头的边界。
 * 从左到右、优先最长的词，互不重叠。
 */
export function applyLexicon(str, bounds, words = BUILTIN_WORDS) {
  const sorted = [...new Set(words)].filter(Boolean).sort((a, b) => b.length - a.length);
  const taken = new Array(str.length).fill(false);
  const hits = [];
  for (const w of sorted) {
    let from = 0;
    for (;;) {
      const i = str.indexOf(w, from);
      if (i < 0) break;
      let free = true;
      for (let k = i; k < i + w.length; k++) if (taken[k]) { free = false; break; }
      if (free) {
        for (let k = i; k < i + w.length; k++) taken[k] = true;
        hits.push([i, i + w.length]);
      }
      from = i + 1;
    }
  }
  const out = new Set(bounds);
  for (const [a, b] of hits) {
    for (let k = a + 1; k < b; k++) out.delete(k);
    out.add(a);
    out.add(b);
  }
  return out;
}
