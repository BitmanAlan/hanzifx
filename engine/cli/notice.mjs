#!/usr/bin/env node
// 生成仓库根目录的 NOTICE.md：npm 依赖（含间接依赖）、外部程序、全部登记的字体、各风格 meta.json 里声明的出处（credits）。
// 不手改；改了依赖、字体或风格的 credits 就重跑：
//   node cli/notice.mjs           写 ../NOTICE.md
//   node cli/notice.mjs --check   只核对 NOTICE.md 是不是最新的，不是就退出码 1（给 CI 和提交前检查用）
// 风格只收 git 里已经提交的（git ls-files），这样在干净的检出上（CI）生成结果一样，别人还没提交的风格也不会混进来。
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { spawnSync } from 'node:child_process';
import { ENGINE_DIR, loadRegistry } from './lib/fonts.mjs';
import { REPO_ROOT } from './lib/server.mjs';
import { parseArgs } from './lib/args.mjs';

const args = parseArgs(process.argv.slice(2));
const OUT = join(REPO_ROOT, 'NOTICE.md');
const cell = (s) => String(s ?? '').replace(/\|/g, '｜').replace(/\n/g, ' ');

// ---------- npm 依赖 ----------
const lock = JSON.parse(await readFile(join(ENGINE_DIR, 'package-lock.json'), 'utf8'));
const rows = [];
for (const [path, info] of Object.entries(lock.packages)) {
  if (!path.startsWith('node_modules/')) continue;
  const name = path.slice('node_modules/'.length);
  let license = info.license;
  let licenseFile = '';
  try {
    const dir = join(ENGINE_DIR, path);
    const files = await readdir(dir);
    licenseFile = files.find((f) => /^licen[cs]e/i.test(f)) || '';
    if (!license) license = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8')).license;
  } catch { /* 没装上的可选依赖 */ }
  rows.push({ name, version: info.version, license: license || '未声明', dev: !!info.dev, direct: !!lock.packages[''].dependencies?.[name], licenseFile });
}
rows.sort((a, b) => Number(b.direct) - Number(a.direct) || a.name.localeCompare(b.name));

// ---------- 字体 ----------
const reg = await loadRegistry();
const fontRows = Object.entries(reg).sort(([a], [b]) => a.localeCompare(b));

// ---------- 各风格的出处 ----------
const git = spawnSync('git', ['ls-files', '--', 'styles/*/meta.json'], { cwd: REPO_ROOT, encoding: 'utf8' });
let metaPaths;
if (git.status === 0 && git.stdout.trim()) metaPaths = git.stdout.trim().split('\n');
else {
  // 不在 git 仓库里（比如解压的发布包）：扫 styles/ 目录
  metaPaths = [];
  for (const d of (await readdir(join(REPO_ROOT, 'styles'))).sort()) metaPaths.push(`styles/${d}/meta.json`);
}
const styles = [];
for (const p of metaPaths.sort()) {
  if (p.startsWith('styles/draft-')) continue; // 还没分配编号、没合并的新风格不收
  try {
    const m = JSON.parse(await readFile(join(REPO_ROOT, p), 'utf8'));
    styles.push({ code: m.code, name: m.name, dir: p.replace(/\/meta\.json$/, ''), credits: m.credits || [] });
  } catch { /* 不是风格目录 */ }
}

const md = [
  '# NOTICE',
  '',
  '本仓库用到的第三方软件和字体，以及各风格自己声明的出处。由 `node engine/cli/notice.mjs` 生成，不要手改；`--check` 只核对是不是最新。',
  'Third-party software and fonts used in this repository, plus the credits each style declares. Generated by `node engine/cli/notice.mjs`; do not edit by hand. `--check` only verifies it is up to date.',
  '',
  '仓库各部分（代码、说明文档、样片、字体）各用什么许可证，见 `docs/LICENSING.md`。 / See `docs/LICENSING.md` for the license of each part of this repository (code, docs, demos, fonts).',
  '',
  '## 1. npm 依赖 / npm dependencies（engine/）',
  '',
  '| 包 / Package | 版本 / Version | 许可证 / License | 直接依赖 / Direct | 许可证文件 / License file |',
  '|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.direct ? '是 / yes' : '间接 / indirect'} | ${r.licenseFile || '（包里没有单独的许可证文件 / none in package）'} |`),
  '',
  'jieba-wasm 的 wasm 里内嵌了 jieba-rs（MIT，messense）的词典 `jieba/src/data/dict.txt`，该词典来自 jieba（MIT，Sun Junyi，github.com/fxsjy/jieba）。',
  'The jieba-wasm binary embeds the dictionary `jieba/src/data/dict.txt` from jieba-rs (MIT, messense), which comes from jieba (MIT, Sun Junyi, github.com/fxsjy/jieba).',
  '',
  '## 2. 外部程序（不打包、不链接，只作为命令调用） / External programs (not bundled or linked; invoked as commands)',
  '',
  '- ffmpeg / ffprobe：用户自己安装。我们调用 libx264、prores_ks、libvpx-vp9 编码器，许可证随用户装的那份 ffmpeg 构建（LGPL 或 GPL）。 / Installed by the user; licensed per the user\'s ffmpeg build (LGPL or GPL).',
  '- Chromium（chrome-headless-shell，由 playwright-core 下载）或用户本机的 Google Chrome。 / Chromium (chrome-headless-shell, downloaded by playwright-core) or the user\'s local Google Chrome.',
  '',
  '## 3. 字体 / Fonts',
  '',
  '字体文件不在仓库里，由 `npm run fonts` 按 `engine/fonts/registry.json` 里钉死的地址下载并核对 sha256；导出的视频和在线画廊里只嵌入用到的字的子集。许可证原文在 `engine/fonts/LICENSES/`，来源和覆盖情况见 `engine/FONTS.md`。',
  'Font files are not in the repository. `npm run fonts` downloads them from pinned URLs in `engine/fonts/registry.json` and verifies their sha256. Exported videos and the online gallery embed subsets of the glyphs used. License texts: `engine/fonts/LICENSES/`; sources and coverage: `engine/FONTS.md`.',
  '',
  '| 登记名 / ID | 字体 / Font | 许可证 / License | 保留字体名 / Reserved Font Name | 版权 / Copyright | 上游 / Upstream |',
  '|---|---|---|---|---|---|',
  ...fontRows.map(([id, f]) => `| ${id} | ${cell(f.name)} | ${f.license} | ${cell(f.reservedFontName || '无 / none')} | ${cell(f.copyright || '')} | ${f.upstream || ''} |`),
  '',
  '## 4. 各风格声明的出处 / Credits declared by each style',
  '',
  '来自各风格 `meta.json` 的 `credits`。「参考效果」只参考公开播出或发布的效果，没有用任何人的素材。',
  'From the `credits` field of each style\'s `meta.json`. "Reference" entries only describe publicly visible effects that were studied; no third-party material is included.',
  '',
  ...styles.flatMap((s) => [
    `### ${s.code} ${s.name}（\`${s.dir}\`）`,
    '',
    ...(s.credits.length ? s.credits.map((c) => `- ${cell(c.what)}：${cell(c.name)}${c.license && c.license !== '—' ? `（${cell(c.license)}）` : ''}${c.url ? ` ${c.url}` : ''}`) : ['- （没有声明 / none declared）']),
    '',
  ]),
].join('\n');

const current = await readFile(OUT, 'utf8').catch(() => '');
if (args.check) {
  if (current !== md) { console.error(`✗ ${relative(process.cwd(), OUT)} 不是最新的，跑一遍 node engine/cli/notice.mjs 更新`); process.exit(1); }
  console.error(`✓ ${relative(process.cwd(), OUT)} 是最新的（依赖 ${rows.length} 个，字体 ${fontRows.length} 款，风格 ${styles.length} 个）`);
} else if (current !== md) {
  await writeFile(OUT, md);
  console.error(`写到 ${relative(process.cwd(), OUT)}（依赖 ${rows.length} 个，字体 ${fontRows.length} 款，风格 ${styles.length} 个）`);
} else console.error('NOTICE.md 已经是最新的');
